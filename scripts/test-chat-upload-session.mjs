import assert from 'node:assert/strict';
import {createChatUploadSession,uniqueUploadName} from '../assets/js/pages/shared/chat-upload-session.js';
import {quoteAttachmentStoragePath} from '../assets/js/pages/shared/chat-attachments.js';
const removed=[];
const session=createChatUploadSession(async path=>removed.push(path));
const first=session.begin('one','one/a');
const second=session.begin('two','two/b');
assert.equal(await session.complete(first),false);
assert.deepEqual(removed,['one/a']);
assert.equal(await session.complete(second),true);
session.discard();
assert.deepEqual(removed,['one/a','two/b']);
const sent=session.begin('two','two/c');
await session.complete(sent);session.sent();session.discard();
assert.deepEqual(removed,['one/a','two/b']);
const failed=session.begin('two','two/d');await session.failed(failed,true);
assert.deepEqual(removed,['one/a','two/b','two/d']);
assert.notEqual(uniqueUploadName('same.pdf'),uniqueUploadName('same.pdf'));
const path='quotes/a/attachments/file.pdf';
const url='https://firebasestorage.googleapis.com/v0/b/worklist-1e83a.firebasestorage.app/o/'+encodeURIComponent(path);
assert.equal(quoteAttachmentStoragePath('a',{path,url}),path);
assert.equal(quoteAttachmentStoragePath('b',{path,url}),'');
assert.equal(quoteAttachmentStoragePath('a',{path:'quotes/a/admin/file.pdf'}),'');
assert.equal(quoteAttachmentStoragePath('a',{path,url:'https://example.com/file.pdf'}),'');
console.log('chat upload isolation, cleanup and attachment path tests passed');
