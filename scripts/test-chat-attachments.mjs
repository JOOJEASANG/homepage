import assert from 'node:assert/strict';
import { chatStoragePath, renderChatAttachment, renderChatImage, deleteChatAttachment } from '../assets/js/pages/shared/chat-attachments.js';
const path='quotes/order-a/admin/시안.png';
const url='https://firebasestorage.googleapis.com/v0/b/worklist-1e83a.firebasestorage.app/o/'+encodeURIComponent(path)+'?alt=media&token=example';
const msg={id:'m1',sender:'admin',type:'file',fileName:'시안.png',filePath:path,fileURL:url,isProof:true,text:'<script>x</script>'};
assert.equal(chatStoragePath('order-a',msg),path);
assert.equal(chatStoragePath('order-b',msg),'');
assert.equal(chatStoragePath('order-a',{...msg,filePath:'quotes/order-a/attachments/private.pdf'}),'');
assert.equal(chatStoragePath('order-a',{...msg,sender:'customer'}),'');
assert.equal(chatStoragePath('order-a',{...msg,filePath:''}),path);
assert.match(renderChatAttachment(msg), /<img src=/);
assert.match(renderChatAttachment(msg), /시안 · 확인 대기/);
assert.match(renderChatAttachment(msg), /&lt;script&gt;/);
assert.equal(renderChatImage({...msg,fileURL:'javascript:alert(1)'}),'');
assert.equal(renderChatImage({...msg,fileName:'시안.pdf'}),'');
const events=[];
const args={quoteId:'order-a',msg,deleteStorage:async p=>events.push(p),deleteRecord:async()=>events.push('record')};
await deleteChatAttachment(args);
assert.deepEqual(events,[path,'record']);
events.length=0;
await assert.rejects(deleteChatAttachment({...args,deleteStorage:async()=>{throw Object.assign(Error('denied'),{code:'storage/unauthorized'});}}),/denied/);
assert.deepEqual(events,[]);
await deleteChatAttachment({...args,deleteStorage:async()=>{throw Object.assign(Error('missing'),{code:'storage/object-not-found'});}});
assert.deepEqual(events,['record']);
await assert.rejects(deleteChatAttachment({...args,quoteId:'other'}),/경로/);
console.log('chat attachment preview and safe storage-first deletion tests passed');
