function addSeedButton() {
  const resetBtn = document.getElementById('resetBtn');
  if (!resetBtn || document.getElementById('seedDefaultFaqBtn')) return;
  const btn = document.createElement('button');
  btn.id = 'seedDefaultFaqBtn';
  btn.type = 'button';
  btn.className = 'btn btn-primary';
  btn.innerHTML = '<i class="fas fa-wand-magic-sparkles"></i> 기본 FAQ 넣기';
  resetBtn.insertAdjacentElement('afterend', btn);
  btn.addEventListener('click', seedDefaultFaqs);
}

async function seedDefaultFaqs() {
  const btn = document.getElementById('seedDefaultFaqBtn');
  if (!confirm('출력/제본/파일접수/스캔/결제/방문수령 FAQ 기본 데이터 ' + DEFAULT_FAQS.length + '개를 등록할까요? 기존 기본 FAQ는 같은 ID 기준으로 업데이트됩니다.')) return;
  try {
    if (btn) { btn.disabled = true; btn.textContent = '등록 중...'; }
    for (const item of DEFAULT_FAQS) {
      await setDoc(doc(db, 'faq', item.id), {
        category: item.category,
        question: item.question,
        answer: item.answer,
        keywords: item.keywords,
        order: item.order,
        isActive: true,
        source: 'defaultSeed',
        updatedAt: serverTimestamp(),
      }, { merge: true });
    }
    alert('기본 FAQ ' + DEFAULT_FAQS.length + '개 등록이 완료되었습니다. 이제 FAQ 관리에서 직접 수정할 수 있습니다.');
  } catch (e) {
    alert('기본 FAQ 등록 실패: ' + (e.message || e));
  } finally {
    if (btn) { btn.disabled = false; btn.innerHTML = '<i class="fas fa-wand-magic-sparkles"></i> 기본 FAQ 넣기'; }
  }
}

if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', addSeedButton, { once: true });
else addSeedButton();
setTimeout(addSeedButton, 1000);
