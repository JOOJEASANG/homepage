export function normalizeGuideTitle(title) {
    return String(title || '').replace(/^\s*\d+\s*[.．]\s*/, '').trim();
}
export function getGuideDetail(title) {
    const normalized = normalizeGuideTitle(title);
    return GUIDE_DETAILS.find(item => item.title === normalized) || null;
}
const escapeHtml = value => String(value).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
export function renderGuideDetails(title) {
    const item = getGuideDetail(title);
    if (!item) return '';
    const list = (items, tag) => `<${tag}>${items.map(step => `<li>${escapeHtml(step)}</li>`).join('')}</${tag}>`;
    return `<h2>실무 예시</h2><p>${escapeHtml(item.example)}</p>
<h2>작업 순서</h2>${list(item.steps, 'ol')}
<h2>접수 전 상세 점검</h2>${list(item.checks, 'ul')}
<blockquote><strong>제작 시 참고</strong><p>${escapeHtml(item.note)}</p></blockquote>`;
}
